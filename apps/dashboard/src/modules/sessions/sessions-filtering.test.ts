import { afterEach, expect, it, vi } from "vitest";
import { SESSION_POLL_MS, SESSION_SEARCH_DEBOUNCE_MS } from "./sessions-controller.js";
import { disposeControllers, page, SESSIONS, setup } from "./sessions-controller.fixture.js";
afterEach(disposeControllers);
const FILTERED = { ...SESSIONS, runs: SESSIONS.runs.slice(0, 1) };
async function openSession() {
  const made = setup();
  made.client.history.mockResolvedValue(page("run:one"));
  await made.controller.start();
  await made.controller.select("run:one");
  return made;
}
it("keeps the open session and its history when filters or search change", async () => {
  const { client, controller } = await openSession();
  const opened = controller.state.selected;
  const history = client.history.mock.calls.length;
  await controller.filter({ runState: "active" });
  expect(controller.state).toMatchObject({ runId: "run:one", filters: { runState: "active" } });
  expect(controller.state.selected).toBe(opened);
  expect(controller.state.events).toHaveLength(1);
  // The server answer no longer holds the open session, which stays open anyway.
  client.classes.mockResolvedValueOnce({ ...SESSIONS, runs: [] });
  await controller.filter({ search: "nobody" });
  expect(controller.state.runs).toEqual([]);
  expect(controller.state).toMatchObject({ runId: "run:one", selected: opened });
  expect(controller.state.events).toHaveLength(1);
  expect(client.history).toHaveBeenCalledTimes(history);
  vi.useFakeTimers();
  controller.search({ search: "ada" });
  await vi.advanceTimersByTimeAsync(SESSION_SEARCH_DEBOUNCE_MS);
  expect(controller.state).toMatchObject({ runId: "run:one", selected: opened });
  expect(controller.state.events).toHaveLength(1);
});
it("keeps the rows and clears only the pagination while the server answer is pending", async () => {
  const { client, controller } = await openSession();
  const answer = Promise.withResolvers<typeof SESSIONS>();
  client.classes.mockReturnValueOnce(answer.promise);
  const pending = controller.filter({ search: "ada" });
  expect(controller.state.runs).toEqual(SESSIONS.runs);
  expect(controller.state.next).toBeNull();
  expect(controller.state.moreBusy).toBe(false);
  expect(controller.state.connection).toBe("current");
  answer.resolve(FILTERED);
  await pending;
  expect(controller.state.runs).toEqual(FILTERED.runs);
  expect(controller.state.next).toBe(FILTERED.nextBeforeRunId);
  await controller.more();
  expect(client.classes.mock.lastCall?.[0]).toBe(FILTERED.nextBeforeRunId);
  expect(client.classes.mock.lastCall?.[3]).toEqual({ search: "ada" });
});
it("filters the loaded rows at once while typing and asks the server only after a pause", async () => {
  vi.useFakeTimers();
  const { client, controller } = await openSession();
  const calls = client.classes.mock.calls.length;
  expect(controller.visibleRuns).toEqual(SESSIONS.runs);
  controller.search({ search: "  ADA " });
  expect(controller.state.filters).toEqual({ search: "ADA" });
  expect(controller.visibleRuns.map((run) => run.studentDisplayName)).toEqual(["Ada"]);
  controller.search({ search: "boundary" });
  expect(controller.visibleRuns).toEqual(SESSIONS.runs);
  controller.search({ search: "ada tests" });
  expect(controller.visibleRuns).toEqual([]);
  await vi.advanceTimersByTimeAsync(SESSION_SEARCH_DEBOUNCE_MS - 1);
  expect(client.classes).toHaveBeenCalledTimes(calls);
  controller.search({ search: "ada" });
  await vi.advanceTimersByTimeAsync(SESSION_SEARCH_DEBOUNCE_MS - 1);
  expect(client.classes).toHaveBeenCalledTimes(calls);
  await vi.advanceTimersByTimeAsync(1);
  expect(client.classes).toHaveBeenCalledTimes(calls + 1);
  expect(client.classes.mock.lastCall?.[0]).toBeNull();
  expect(client.classes.mock.lastCall?.[3]).toEqual({ search: "ada" });
  await vi.advanceTimersByTimeAsync(SESSION_POLL_MS / 2);
  expect(client.classes).toHaveBeenCalledTimes(calls + 1);
  expect(SESSION_SEARCH_DEBOUNCE_MS).toBe(300);
});
it("aborts the request a newer search supersedes and ignores its late answer", async () => {
  vi.useFakeTimers();
  const { client, controller } = await openSession();
  const first = Promise.withResolvers<typeof SESSIONS>();
  client.classes.mockReturnValueOnce(first.promise).mockResolvedValueOnce(FILTERED);
  controller.search({ search: "a" });
  await vi.advanceTimersByTimeAsync(SESSION_SEARCH_DEBOUNCE_MS);
  const firstSignal = client.classes.mock.lastCall?.[1];
  expect(firstSignal?.aborted).toBe(false);
  controller.search({ search: "ada" });
  await vi.advanceTimersByTimeAsync(SESSION_SEARCH_DEBOUNCE_MS);
  expect(firstSignal?.aborted).toBe(true);
  expect(client.classes.mock.lastCall?.[1].aborted).toBe(false);
  first.resolve({ ...SESSIONS, runs: [] });
  await vi.advanceTimersByTimeAsync(0);
  expect(controller.state.runs).toEqual(FILTERED.runs);
});
it("keeps polling and paging with the filters the list was last asked with", async () => {
  vi.useFakeTimers();
  const { client, controller } = await openSession();
  controller.search({ search: "ada" });
  await controller.refresh();
  expect(client.classes.mock.lastCall?.[3]).toEqual({});
  await vi.advanceTimersByTimeAsync(SESSION_SEARCH_DEBOUNCE_MS);
  expect(client.classes.mock.lastCall?.[3]).toEqual({ search: "ada" });
});
it("queries a show choice at once, dropping a pending search and keeping the session", async () => {
  vi.useFakeTimers();
  const { client, controller } = await openSession();
  const calls = client.classes.mock.calls.length;
  controller.search({ search: "ada" });
  await controller.filter({ search: "ada", runState: "closed" });
  expect(client.classes).toHaveBeenCalledTimes(calls + 1);
  await vi.advanceTimersByTimeAsync(SESSION_SEARCH_DEBOUNCE_MS);
  expect(client.classes).toHaveBeenCalledTimes(calls + 1);
  expect(controller.state.runId).toBe("run:one");
});
it("applies the typed filters when the class changes during a pending search", async () => {
  vi.useFakeTimers();
  const { client, controller } = await openSession();
  const calls = client.classes.mock.calls.length;
  controller.search({ search: "ada" });
  await controller.chooseClass("class:one");
  expect(client.classes.mock.lastCall?.[3]).toEqual({ search: "ada" });
  await vi.advanceTimersByTimeAsync(SESSION_SEARCH_DEBOUNCE_MS);
  expect(client.classes).toHaveBeenCalledTimes(calls + 1);
  expect(controller.state.runId).toBeNull();
});
it("does not search after the controller is disposed", async () => {
  vi.useFakeTimers();
  const { client, controller } = await openSession();
  const calls = client.classes.mock.calls.length;
  controller.search({ search: "ada" });
  controller.dispose();
  await vi.advanceTimersByTimeAsync(SESSION_SEARCH_DEBOUNCE_MS);
  expect(client.classes).toHaveBeenCalledTimes(calls);
});
it("lists a changed class from the newest session, not from the page cursor", async () => {
  const { client, controller } = await openSession();
  await controller.more();
  expect(client.classes.mock.lastCall?.[0]).toBe(SESSIONS.nextBeforeRunId);
  await controller.chooseClass("class:one");
  expect(client.classes.mock.lastCall?.[0]).toBeNull();
  await controller.refresh();
  expect(client.classes.mock.lastCall?.[0]).toBeNull();
});
